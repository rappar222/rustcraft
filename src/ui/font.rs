pub fn create_font_texture_data() -> (Vec<u8>, u32, u32) {
    let atlas_cols = 16;
    let atlas_rows = 6;
    let width = (atlas_cols * FONT_WIDTH) as u32; // 128
    let height = (atlas_rows * FONT_HEIGHT) as u32; // 48
    let mut pixels = vec![0u8; (width * height * 4) as usize];

    for idx in 0..FONT_CHARS {
        let ch = (32 + idx) as u8 as char;
        let glyph = get_glyph_bitmap(ch);
        let col = idx % atlas_cols;
        let row = idx / atlas_cols;
        let start_x = col * FONT_WIDTH;
        let start_y = row * FONT_HEIGHT;

        for gy in 0..FONT_HEIGHT {
            let row_byte = glyph[gy];
            for gx in 0..FONT_WIDTH {
                let is_on = (row_byte & (0x80 >> gx)) != 0;
                let px = start_x + gx;
                let py = start_y + gy;
                let p_idx = ((py * width as usize + px) * 4) as usize;
                if is_on {
                    pixels[p_idx] = 255;
                    pixels[p_idx + 1] = 255;
                    pixels[p_idx + 2] = 255;
                    pixels[p_idx + 3] = 255;
                } else {
                    pixels[p_idx] = 0;
                    pixels[p_idx + 1] = 0;
                    pixels[p_idx + 2] = 0;
                    pixels[p_idx + 3] = 0;
                }
            }
        }
    }

    (pixels, width, height)
}

pub fn get_char_uv(ch: char) -> [f32; 4] {
    let c = ch as u32;
    let idx = if (32..=126).contains(&c) {
        c - 32
    } else {
        0
    };
    let atlas_cols = 16.0;
    let atlas_rows = 6.0;
    let col = (idx % 16) as f32;
    let row = (idx / 16) as f32;

    let u_min = col / atlas_cols;
    let v_min = row / atlas_rows;
    let u_max = (col + 1.0) / atlas_cols;
    let v_max = (row + 1.0) / atlas_rows;

    [u_min, v_min, u_max, v_max]
}
